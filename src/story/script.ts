// ── کمک‌تابع‌ها برای خوانا ماندن اسکریپت ──
const n = (text: string): Node => ({ t: 'say', text })
const say = (who: string, text: string): Node => ({ t: 'say', who, text })
const bg = (id: string): Node => ({ t: 'bg', id })
const show = (char: string, pos: CharPos = 'center', mood?: string): Node => ({ t: 'show', char, pos, mood })
const hide = (char?: string): Node => ({ t: 'hide', char })
const set = (flags: Flags): Node => ({ t: 'set', flags })
const jump = (to: string): Node => ({ t: 'jump', to })
const fx = (kind: FxKind): Node => ({ t: 'fx', kind })
const chapter = (num: string, title: string): Node => ({ t: 'chapter', num, title })
const when = (cond: (f: Flags) => boolean, then: string, otherwise?: string): Node => ({
  t: 'if',
  cond,
  then,
  else: otherwise,
})

